async def _emit_pod_event(
    pod_uid: str,
    pod_name: str,
    namespace: str,
    *,
    name_prefix: str,
    reason: str,
    action: str,
    message: str,
    event_type: str = "Normal",
) -> None:
    """Create a Kubernetes Event linked to the pod identified by *pod_uid*.

    Shared body for the runtime-guarantee, preemption, and cancellation
    emitters (CODE-REVIEW D3c), which differ only in *name_prefix* / *reason*
    / *action* / *message* / *event_type*.  Uses ``generate_name`` so
    re-emitting for the same pod never 409s (B10).

    Takes the pod **uid** rather than the pod object because that is the only
    field of it this needs (the ``involvedObject`` reference), and the
    lease-denial and admission-paused emitters have a uid in hand without a
    pod: their candidate was never admitted, so re-reading the pod purely to
    fill in an event would be a second API call for a field the caller already
    knows.
    """
    now = datetime.now(timezone.utc)
    event = k8s_client.CoreV1Event(
        metadata=k8s_client.V1ObjectMeta(
            generate_name=name_prefix,
            namespace=namespace,
        ),
        involved_object=k8s_client.V1ObjectReference(
            api_version="v1",
            kind="Pod",
            name=pod_name,
            namespace=namespace,
            uid=pod_uid,
        ),
        reason=reason,
        message=message,
        type=event_type,
        first_timestamp=now,
        last_timestamp=now,
        count=1,
        reporting_component="gpu-reservation-controller",
        action=action,
    )
    log.debug("%s", kv(
        event="k8s.create_event", ns=namespace, pod=pod_name, reason=reason,
    ))
    await _run(_core_v1.create_namespaced_event, namespace, event)


