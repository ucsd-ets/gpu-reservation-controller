# Phases from which a pod never returns to Running — its GPU slot is free and
# it should be released from occupancy.  Defined once here (next to
# get_pod_phase) so the watch loop, the reserved path, and the on-demand path
# all agree on what "terminal" means (CODE-REVIEW D1c).  The on-demand *drop*
# additionally treats "Unknown" as gone-for-placement (TERMINAL_PHASES +
# ("Unknown",)); that is a placement decision, not an occupancy release.
TERMINAL_PHASES = ("Succeeded", "Failed")


def get_pod_phase(pod) -> str:
    """Return the pod's phase string (e.g. "Pending", "Running", "Succeeded", "Failed").

    Returns an empty string if the phase is unavailable.
    """
    return (pod.status.phase if pod.status else None) or ""


def is_terminal_phase(pod) -> bool:
    """Return True if *pod* is in a terminal phase (Succeeded/Failed)."""
    return get_pod_phase(pod) in TERMINAL_PHASES


def get_pod_creation_timestamp(pod) -> Optional[datetime]:
    """Return the pod's ``metadata.creationTimestamp``, or ``None`` if unset."""
    return pod.metadata.creation_timestamp


def get_unschedulable_message(pod) -> str:
    """Return the ``PodScheduled`` condition message, truncated to 120 chars.

    Empty string when there is no such condition.  Owning the pod-object dig
    here keeps ``main.py`` out of ``pod.status.conditions`` internals
    (CODE-REVIEW D10).
    """
    conditions = (pod.status.conditions or []) if pod.status else []
    scheduled = next((c for c in conditions if c.type == "PodScheduled"), None)
    if scheduled is None:
        return ""
    return (scheduled.message or "")[:120]


# The galends/* job-input annotations a pod author writes and this module reads
# (see docs/POD-ANNOTATIONS.md §3).
MIN_RUNTIME_ANNOTATION = "galends/minimum-runtime-seconds"
RUNTIME_GUARANTEE_ANNOTATION = "galends/runtime-guarantee"
USAGE_GROUP_ANNOTATION = "galends/usage-group"

# Recognised values of the galends/runtime-guarantee pod annotation. A set
# rather than a bare literal so an added posture (say a future "soft") is one
# entry plus its handling, not a new parse path.
RUNTIME_GUARANTEE_VALUES = frozenset({"none"})


class AnnotationProblem(NamedTuple):
    """One job-input annotation on a pod that the controller had to ignore.

    ``reason`` is the same vocabulary ``pod.annotation_invalid`` logs --
    ``not_an_integer``, ``not_positive``, ``unrecognised_value`` -- plus
    ``not_enabled``: a well-formed request for something this deployment does
    not offer (``galends/runtime-guarantee`` while best-effort admission is
    off).  ``value`` is the annotation's value exactly as written.
    """

    annotation: str
    value: str
    reason: str


def _parse_min_runtime(raw) -> tuple[Optional[int], Optional[str]]:
    """``(seconds, None)`` for a positive integer, ``(None, reason)`` for any
    other value, ``(None, None)`` when the annotation is absent.

    The single definition of what ``galends/minimum-runtime-seconds`` accepts,
    shared by the logging getter and :func:`get_pod_annotation_problems` so the
    log line and the pod's Event can never disagree about a value.
    """
    if raw is None:
        return None, None
    try:
        value = int(raw)
    except (ValueError, TypeError):
        return None, "not_an_integer"
    if value <= 0:
        return None, "not_positive"
    return value, None


def _parse_runtime_guarantee(raw) -> tuple[Optional[str], Optional[str]]:
    """``(value, None)`` for a recognised value, ``(None, "unrecognised_value")``
    for any other, ``(None, None)`` when the annotation is absent.

    Case and surrounding whitespace are forgiven.  Shared like
    :func:`_parse_min_runtime`, for the same reason.
    """
    if raw is None:
        return None, None
    value = raw.strip().lower() if isinstance(raw, str) else raw
    if value in RUNTIME_GUARANTEE_VALUES:
        return value, None
    return None, "unrecognised_value"


def get_pod_min_runtime_seconds(pod) -> Optional[int]:
    """Read the ``galends/minimum-runtime-seconds`` annotation from *pod*.

    Returns the integer value if the annotation is present and parseable as a
    positive integer, or ``None`` otherwise.

    A non-positive value is rejected like junk, and says so: the floor is what
    makes the annotation mean "run me for at least this long", and ``0`` cannot
    express that.  It reads as a request for no runtime guarantee, which is a
    real thing to want and has its own annotation
    (``galends/runtime-guarantee: none`` -- see
    :func:`get_pod_runtime_guarantee_request`), so the warning names it.  Before
    that annotation existed a ``0`` here silently disqualified the pod from JIT
    admission with nothing logged at any level, and it sat Pending forever.
    """
    annotations: dict = pod.metadata.annotations or {}
    raw = annotations.get(MIN_RUNTIME_ANNOTATION)
    value, reason = _parse_min_runtime(raw)
    if reason == "not_an_integer":
        log.warning("%s", kv(
            event="pod.annotation_invalid",
            ns=pod.metadata.namespace, pod=pod.metadata.name,
            annotation=MIN_RUNTIME_ANNOTATION, value=raw,
            reason="not_an_integer",
        ))
    elif reason == "not_positive":
        log.warning("%s", kv(
            event="pod.annotation_invalid",
            ns=pod.metadata.namespace, pod=pod.metadata.name,
            annotation=MIN_RUNTIME_ANNOTATION, value=raw,
            reason="not_positive",
            detail="use galends/runtime-guarantee=none to request no guarantee",
        ))
    return value


def get_pod_runtime_guarantee_request(pod) -> Optional[str]:
    """Read the ``galends/runtime-guarantee`` annotation from *pod*.

    The pod's own statement of what runtime protection it wants.  Exactly one
    value is defined: ``"none"`` -- admit me with no runtime guarantee at all,
    on idle capacity I will give back the moment anything else needs it.  Such a
    pod is admitted under a zero-length, zero-SU ``kind="best_effort"``
    reservation, so it is preemptible from its first tick.

    Returns the recognised value, or ``None`` when the annotation is absent or
    unrecognised.  An unrecognised value logs ``pod.annotation_invalid`` and
    falls through to ordinary handling rather than failing the pod: the same
    tolerant-parse-and-say-so posture ``config.py`` takes, for the same reason
    (an operator who set something and saw no effect can find out why).

    Deliberately separate from ``galends/minimum-runtime-seconds``, which sizes
    a *lease*.  The two compose -- a pod may name a runtime and still waive the
    guarantee -- and keeping the posture out of the duration means neither has
    to carry a sentinel value for the other's sake.
    """
    annotations: dict = getattr(pod.metadata, "annotations", None) or {}
    raw = annotations.get(RUNTIME_GUARANTEE_ANNOTATION)
    value, reason = _parse_runtime_guarantee(raw)
    if reason is not None:
        log.warning("%s", kv(
            event="pod.annotation_invalid",
            ns=pod.metadata.namespace, pod=pod.metadata.name,
            annotation=RUNTIME_GUARANTEE_ANNOTATION, value=raw,
            reason=reason,
            detail="expected: " + ", ".join(sorted(RUNTIME_GUARANTEE_VALUES)),
        ))
    return value


def get_pod_annotation_problems(
    pod, *, best_effort_enabled: bool
) -> list[AnnotationProblem]:
    """Every job-input annotation on *pod* that the controller will ignore.

    The pod-facing counterpart of the ``pod.annotation_invalid`` log line: the
    same verdicts (the parse is shared), gathered so the pod's owner can be told
    in an Event rather than only an operator in the log.  Pure -- no logging;
    the getters above already log each rejection.

    ``galends/runtime-guarantee`` is reported as ``not_enabled`` whatever it
    says while *best_effort_enabled* is off, because then no value of it is
    honoured, and telling someone their value is merely misspelled would send
    them round a second time.  ``galends/usage-group`` is never reported: it is
    free text the app judges (an unknown group is the app's 404 to relay).
    """
    annotations: dict = getattr(pod.metadata, "annotations", None) or {}
    problems: list[AnnotationProblem] = []

    raw = annotations.get(MIN_RUNTIME_ANNOTATION)
    _value, reason = _parse_min_runtime(raw)
    if reason is not None:
        problems.append(AnnotationProblem(MIN_RUNTIME_ANNOTATION, str(raw), reason))

    raw = annotations.get(RUNTIME_GUARANTEE_ANNOTATION)
    if raw is not None:
        _value, reason = _parse_runtime_guarantee(raw)
        if not best_effort_enabled:
            reason = "not_enabled"
        if reason is not None:
            problems.append(
                AnnotationProblem(RUNTIME_GUARANTEE_ANNOTATION, str(raw), reason)
            )
    return problems


def get_pod_usage_group(pod) -> Optional[str]:
    """Read the ``galends/usage-group`` annotation from *pod*.

    Names the usage group a JIT on-demand lease should be created under —
    ``group_name`` is a required natural key on the app's lease-create endpoint
    (RESERVATION-API.md §"Creating on-demand reservations": the user supplies
    their group via this pod annotation).  Only consulted when
    ``REQUIRED_GROUP_LABEL`` is disabled; when that feature is on, the group
    label is both the match axis and the group source.  Returns ``None`` when
    the annotation is absent or empty.
    """
    annotations: dict = getattr(pod.metadata, "annotations", None) or {}
    return annotations.get(USAGE_GROUP_ANNOTATION) or None


def get_pod_gpu_count(pod) -> int:
    """Sum nvidia.com/gpu resource requests across all containers in *pod*."""
    total = 0
    for container in pod.spec.containers or []:
        requests = (
            (container.resources.requests or {}) if container.resources else {}
        )
        try:
            total += int(requests.get("nvidia.com/gpu", 0))
        except (ValueError, TypeError):
            pass
    return total


def get_pod_booking_reference(pod) -> Optional[str]:
    """Return the ``galends/booking-reference`` annotation value, or ``None``."""
    annotations: dict = getattr(pod.metadata, "annotations", None) or {}
    return annotations.get("galends/booking-reference")


# The annotation namespace this system owns.  Every key the controller writes,
# and every key it reads off a pod, carries it -- so the prefix is also what marks
# a pod annotation as *about* the reservation system, and therefore worth
# forwarding to the app with a JIT admission ask (see
# ``get_pod_galends_annotations``).  Matched with the trailing slash, which is
# what keeps an unrelated ``galends.example.com/...`` key out.
GALENDS_PREFIX = "galends/"

# Bounds applied when forwarding those annotations off-cluster.  Their values are
# whatever the pod's creator wrote, and Kubernetes caps *all* annotations on an
# object at 256 KiB -- which an admission batch would otherwise carry per
# candidate, every 2-5 minutes, for as long as the pod stays Pending.  Capping
# here rather than in the app is deliberate: the app's schema is lenient on
# purpose, because a rejected candidate 422s the whole batch (RESERVATION-API.md
# "POST /api/reservations/ondemand-admission"), so the controller must never send
# something the far end would refuse.
GALENDS_ANNOTATION_MAX_KEYS = 32
GALENDS_ANNOTATION_MAX_VALUE = 1024


def get_pod_galends_annotations(pod) -> dict[str, str]:
    """Return the pod's ``galends/``-prefixed annotations, bounded for the wire.

    Unlike the single-key readers above this makes no judgement about *which*
    keys matter: the app is the consumer, and the whole point of forwarding them
    is that a future admission policy can weigh a signal the controller does not
    itself understand.  So every key in the namespace goes, including the ones
    the controller wrote itself (``booking-reference``, the guarantee and
    termination-warning keys) -- a candidate awaiting admission generally has
    none of those, but a re-queued pod may.

    Two bounds apply, both silent-by-design on the value side and logged on the
    key side.  Keys are taken in sorted order and capped at
    ``GALENDS_ANNOTATION_MAX_KEYS`` -- sorted, so the same pod always yields the
    same subset rather than flapping between attempts -- and each value is
    truncated to ``GALENDS_ANNOTATION_MAX_VALUE`` characters.  A truncated value
    is still recognisably itself; a dropped key is not, which is why only the
    latter says so.
    """
    annotations: dict = getattr(pod.metadata, "annotations", None) or {}
    selected = {
        key: value for key, value in annotations.items()
        if key.startswith(GALENDS_PREFIX)
    }
    kept = sorted(selected)[:GALENDS_ANNOTATION_MAX_KEYS]

    dropped = len(selected) - len(kept)
    if dropped:
        # DEBUG, not WARNING: this repeats on every admission attempt for as long
        # as the pod waits, and the same reasoning that puts
        # ``k8s.node_capacity_forced`` at DEBUG applies.  It exists at all so an
        # operator whose annotation never reached the app can find out why.
        log.debug("%s", kv(
            event="pod.annotations_truncated",
            ns=pod.metadata.namespace, pod=pod.metadata.name, count=dropped,
        ))

    return {
        key: str(selected[key])[:GALENDS_ANNOTATION_MAX_VALUE] for key in kept
    }


def utc_iso(dt: datetime) -> str:
    """Render *dt* in the wire format every ``galends/*`` timestamp annotation uses.

    ``YYYY-MM-DDTHH:MM:SSZ``, the format ``docs/POD-ANNOTATIONS.md`` promises
    in-pod consumers.  This is its single definition, so a writer here and the
    diff-and-skip comparisons in ``main`` (which rebuild the string to decide
    whether a re-patch is needed) cannot drift apart into a per-tick re-patch
    loop.

    An aware datetime is normalised to UTC first, so a value that reached us on
    a non-UTC offset is not mislabelled ``Z``.  A naive one is assumed to
    already be UTC — every datetime in this codebase is built with
    ``timezone.utc``, so that is a defensive fallback, not a supported input.
    """
    if dt.tzinfo is not None:
        dt = dt.astimezone(timezone.utc)
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


# Timezone the human-readable prose renders in — Kubernetes Event messages and
# the ``galends/termination-warning-message`` annotation.  ``None`` means the
# process's local zone (what ``TZ`` sets), which is also the default — so a
# deployment that sets neither variable still renders UTC.  A module global set
# once at startup rather than a threaded parameter: the emitters are reached
# from call sites (``_record_guarantee`` and friends) that carry no ``Config``,
# and this module already holds startup-initialised globals for the API
# clients.
_display_tz: Optional[tzinfo] = None


def set_display_timezone(tz: Optional[tzinfo]) -> None:
    """Set the zone ``local_display`` renders in (``Config.display_timezone``)."""
    global _display_tz
    _display_tz = tz


def format_local(dt: datetime, tz: Optional[tzinfo]) -> str:
    """Render *dt* in *tz* for a human to read, e.g. ``2026-08-21 10:30:16 PDT``.

    The counterpart to ``utc_iso``, and deliberately *not* a replacement for it:
    a stored instant, a ``galends/*`` timestamp annotation and every log field
    stay UTC (``docs/POD-ANNOTATIONS.md`` promises consumers that wire format,
    and ``main``'s diff-and-skip reconciles rebuild those strings to decide
    whether to re-patch).  Only prose a person reads is localised.

    *tz* of ``None`` means the process's local zone, resolved per instant by
    ``astimezone`` — so a daemon that started in PST renders a PDT instant
    correctly rather than freezing the offset it booted with.

    The zone is always named, because a bare local timestamp is ambiguous and
    one labelled ``Z`` would be wrong.  ``%Z`` gives the abbreviation for a
    named zone and can come back empty for a bare fixed offset, so that case
    falls back to the numeric offset.

    A naive instant is assumed to be UTC, matching ``utc_iso`` — ``astimezone``
    would otherwise read it as *local* time, so the two helpers would disagree
    about the same input.  As there, that is a defensive fallback rather than a
    supported input: every datetime in this codebase is built ``timezone.utc``.
    """
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    local = dt.astimezone(tz)
    label = local.strftime("%Z") or local.strftime("%z")
    return f"{local.strftime('%Y-%m-%d %H:%M:%S')} {label}".strip()


def local_display(dt: datetime) -> str:
    """``format_local`` against the startup-configured display zone."""
    return format_local(dt, _display_tz)


# Annotation keys describing the reservation an admitted pod is running under,
# stamped alongside the runtime guarantee (see annotate_runtime_guarantee).
# ``galends/guaranteed-until`` is the end of the guarantee *chain*, which says
# nothing about the pod's own window or how it was obtained — these fill that
# gap so an in-pod widget can distinguish "your 14:00 booking" from "a
# just-in-time lease the controller minted for you", and show how much of a
# booking the pod is actually using.  Informational only, like every other
# galends/* annotation the controller writes: nothing reads them back.
RESERVATION_KIND = "galends/reservation-kind"
RESERVATION_START = "galends/reservation-start"
RESERVATION_END = "galends/reservation-end"
RESERVATION_GPU_COUNT = "galends/reservation-gpu-count"
GPU_CLASS_NAME = "galends/gpu-class-name"

# Write-once: the instant the controller first admitted this pod.  Deliberately
# NOT rewritten when the pod is re-linked to another reservation (adoption /
# lease-to-booking merge) — a re-link is not a new admission, and resetting it
# would restart a session-elapsed clock mid-job.  See ReservationFacts.
ADMITTED_AT = "galends/admitted-at"


@dataclass(frozen=True)
class ReservationFacts:
    """Plain-field digest of the reservation a pod is admitted under.

    Built in ``main`` from a ``schemas.ReservationResponse`` so this module
    stays free of the Pydantic response models — the mirror of the
    ``PodRuntimeView`` convention that keeps ``controller`` free of Kubernetes
    shapes.

    Every field describes the *reservation*, not the pod: ``gpu_count`` is what
    the reservation reserves (which a consumer compares against the pod's own
    request to show "using 1 of the 4 GPUs you booked"), and
    ``start_utc``/``end_utc`` are its own window — not the guarantee chain end
    that ``galends/guaranteed-until`` carries.
    """

    # "booking" | "on_demand" (a just-in-time lease) | "best_effort" (a
    # zero-length stub for a pod that asked for no runtime guarantee)
    kind: str
    start_utc: datetime
    end_utc: datetime
    gpu_count: int
    gpu_class_name: str  # human display name, e.g. "NVIDIA H100 80GB"


# Annotation keys for the informational termination-warning stamped on a pod at
# risk of demand-driven preemption (see main._apply_termination_warnings).  Like
# the runtime-guarantee annotations, these are best-effort and never read back
# to make a decision; the sweep recomputes risk live from reservation state.
TERMINATION_WARNING_AT = "galends/termination-warning-at"
TERMINATION_WARNING_RISK = "galends/termination-warning-risk"
TERMINATION_WARNING_MESSAGE = "galends/termination-warning-message"


def get_pod_termination_warning(pod) -> tuple[Optional[str], Optional[str]]:
    """Return the pod's ``(termination-warning-at, termination-warning-risk)``.

    Either element is ``None`` when its annotation is absent.  Used only to
    diff the desired warning against what the pod already carries, so a
    repeated sweep does not re-patch an unchanged warning.
    """
    annotations: dict = getattr(pod.metadata, "annotations", None) or {}
    return (
        annotations.get(TERMINATION_WARNING_AT),
        annotations.get(TERMINATION_WARNING_RISK),
    )


# Annotation key for the pod's live guarantee status: whether it is still inside
# its runtime guarantee (``"guaranteed"``) or running past it (``"overstay"``).
# It rides alongside the existing ``galends/guaranteed-until`` (the guarantee-end
# instant, kept live) as a general status surface, stamped at admission and
# refreshed as the status changes (guarantee lapsing, adoption/merge).  Like the
# other guarantee/termination annotations it is best-effort and never read back
# to make a decision.
GUARANTEE_STATUS = "galends/guarantee-status"
GUARANTEE_STATUS_GUARANTEED = "guaranteed"
GUARANTEE_STATUS_OVERSTAY = "overstay"


def get_pod_guarantee_status(pod) -> tuple[Optional[str], Optional[str]]:
    """Return the pod's ``(guarantee-status, guaranteed-until)`` annotations.

    Either element is ``None`` when its annotation is absent.  Used only to
    diff the desired status against what the pod already carries, so a repeated
    reconcile does not re-patch an unchanged status.
    """
    annotations: dict = getattr(pod.metadata, "annotations", None) or {}
    return (
        annotations.get(GUARANTEE_STATUS),
        annotations.get("galends/guaranteed-until"),
    )


def get_pod_reservation_facts(pod) -> tuple:
    """Return the pod's five ``galends`` reservation-fact annotations, raw.

    Order matches ``ReservationFacts``: ``(kind, start, end, gpu_count,
    gpu_class_name)``; any element is ``None`` when its annotation is absent.
    Values are the stored strings, **not** parsed — the reconcile in ``main``
    compares them against freshly rendered strings (``utc_iso`` / ``str``), so
    round-tripping through a parse would only introduce a way for the two sides
    to disagree about formatting and re-patch every tick.

    ``galends/admitted-at`` is deliberately absent: it is stamped once at first
    admission and must never be refreshed, so nothing should be diffing it.
    """
    annotations: dict = getattr(pod.metadata, "annotations", None) or {}
    return (
        annotations.get(RESERVATION_KIND),
        annotations.get(RESERVATION_START),
        annotations.get(RESERVATION_END),
        annotations.get(RESERVATION_GPU_COUNT),
        annotations.get(GPU_CLASS_NAME),
    )


# Prefix recorded in a galends/booking-reference value.  Every admitted pod is a
# real reservation now (the lease model requests one just-in-time rather than
# placing onto an ad-hoc block), so there is only one kind.  Construction
# (make_booking_reference) and parsing (parse_booking_reference) live together
# so a renamed prefix cannot silently break occupancy reconstruction.
_BOOKING_REFERENCE_PREFIX = "res-"


def make_booking_reference(reservation_id: int) -> str:
    """Build a ``galends/booking-reference`` value for *reservation_id*.

    The result round-trips through ``parse_booking_reference``.
    """
    return f"{_BOOKING_REFERENCE_PREFIX}{reservation_id}"


def parse_booking_reference(reference: Optional[str]) -> Optional[int]:
    """Extract the reservation id embedded in a ``galends/booking-reference`` value.

    ``"res-42"`` returns ``42``.  Returns ``None`` for an unrecognised prefix,
    a non-integer suffix, or ``None``/empty input.  This is the single key
    used to reconstruct occupancy from the cluster.
    """
    if not reference or not reference.startswith(_BOOKING_REFERENCE_PREFIX):
        return None
    try:
        return int(reference[len(_BOOKING_REFERENCE_PREFIX):])
    except ValueError:
        return None


def pod_has_toleration(pod, key: str, value: str, effect: str) -> bool:
    """Return True if *pod* already carries the named toleration."""
    for t in pod.spec.tolerations or []:
        if t.key == key and t.value == value and t.effect == effect:
            return True
    return False


def _pod_has_any_reservation_toleration(pod, toleration_key: str) -> bool:
    """Return True if *pod* has any toleration whose key equals *toleration_key*.

    Key-only match (any value/effect) — used to identify pods that were
    admitted by this controller regardless of the GPU-class value.
    """
    return any(t.key == toleration_key for t in (pod.spec.tolerations or []))


# Scheduler-message parsing for guard 1 (see is_gpu_gated_pending).
#
# The message is an aggregate of per-node filter verdicts.  kube-scheduler runs
# Filter plugins in a fixed order and records only the *first* one that rejects
# a given node, so a node knocked out by TaintToleration never reaches
# NodeResourcesFit — the constraint that shapes everything below.
_INSUFFICIENT_RE = re.compile(r"Insufficient (\S+)")
_TAINT_BUCKET_RE = re.compile(r"untolerated taint")
# Older kube-scheduler named the offending taint inline —
# "had untolerated taint {key=value: NoSchedule}" — while current versions emit
# an anonymous count ("25 node(s) had untolerated taint(s)").  Both are handled.
_NAMED_TAINT_RE = re.compile(r"untolerated taint \{([^}=:]+)")


def is_gpu_gated_pending(pod, taint_key: str) -> Optional[bool]:
    """Guard 1: is *pod* Pending for something a lease + toleration could fix?

    Inspects ``pod.status.conditions[type=PodScheduled]`` and classifies the
    scheduling failure.  The question is deliberately *not* "is the pod short of
    GPUs" — for an unadmitted candidate the scheduler cannot answer that.  The
    controller's GPU nodes are tainted ``<taint_key>=<class>:NoSchedule``, a
    candidate by definition does not tolerate that yet, and ``TaintToleration``
    runs ahead of ``NodeResourcesFit`` in the default filter order — so every
    node of the pod's own class is rejected on the taint and never produces an
    ``Insufficient nvidia.com/gpu`` verdict at all.  Requiring that string as
    the positive signal held every candidate at "indeterminate" forever on any
    correctly taint-gated cluster.

    So the message is read for what it *can* still say reliably: which blockers
    rule the pod out for reasons a lease cannot fix.

    Returns:
        ``True``  — the scheduler has ruled and named no blocker the controller
                    cannot fix.  Either GPU shortage is named outright (a class
                    whose nodes are untainted), or nodes were rejected on an
                    untolerated taint that may well be ours.  Proceed.
        ``False`` — confirmed blocker we cannot fix: an ``Insufficient
                    <non-GPU-resource>``; or no node was rejected on *any*
                    taint (so our toleration changes nothing) with no GPU
                    shortage named either; or every taint the message names is
                    somebody else's.  Drop the candidate.
        ``None``  — no scheduling verdict yet: the pod is not Pending, carries
                    no ``PodScheduled`` condition, is not ``Unschedulable``, or
                    the message is empty.  Keep the candidate and retry; this
                    is the transient case the MODIFIED fast path in
                    ``pod_watch_loop`` exists to shorten.

    **Known limitation**, inherent to the filter ordering above: a candidate
    blocked by a *second* constraint on its own class's nodes — insufficient
    cpu/memory there, an unrelated taint, an unsatisfiable volume — is
    invisible here, because those nodes never get past the taint filter to
    report it.  Such a pod classifies ``True``, is granted a lease, and stays
    Pending under it.  The backstops are guard 3 (a stuck holder freezes the
    class), the lease's own short expiry, and ``_teardown_ondemand_lease``.
    """
    if get_pod_phase(pod) != "Pending":
        return None

    conditions = (pod.status.conditions or []) if pod.status else []
    scheduled = next((c for c in conditions if c.type == "PodScheduled"), None)
    if scheduled is None or scheduled.status != "False":
        return None
    if scheduled.reason != "Unschedulable":
        return None

    message = scheduled.message or ""
    if not message:
        return None

    # (1) Any non-GPU resource shortage rules the pod out, even when GPU is
    # also short — our toleration alone cannot help it.  Strip trailing
    # punctuation from the match: the scheduler appends commas and periods
    # (e.g. "Insufficient nvidia.com/gpu, 3 Insufficient memory.").
    for m in _INSUFFICIENT_RE.finditer(message):
        if m.group(1).rstrip(".,;)") != "nvidia.com/gpu":
            return False

    # (2) GPU shortage named outright — the unambiguous case, and the only one
    # the pre-taint-aware version of this guard could recognise.  It still
    # occurs for a class whose nodes carry no reservation taint.
    if "Insufficient nvidia.com/gpu" in message:
        return True

    # (3) No node was rejected on a taint at all, and no GPU shortage was
    # named: whatever is blocking this pod, adding a toleration will not move
    # it (a cluster-wide affinity/selector mismatch, an unbindable volume).
    if not _TAINT_BUCKET_RE.search(message):
        return False

    # (4) Taints did reject nodes.  When the scheduler names them, ours has to
    # be among them for a lease to help; when it only counts them
    # (current kube-scheduler), assume it may be and proceed.
    named = {m.group(1).strip() for m in _NAMED_TAINT_RE.finditer(message)}
    if named and taint_key not in named:
        return False

    return True


