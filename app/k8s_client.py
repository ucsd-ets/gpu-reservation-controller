# Node annotation overriding the GPU capacity the controller reads off a node.
# Unlike every other ``galends/*`` key in this module it is *read* rather than
# written, and it lives on a **node** rather than a pod: it is an operator's
# statement about how many GPUs of that node the reservation system may account
# for, which need not be what the device plugin advertises (a node whose GPUs
# are failing, held back for non-reservation work, or misreported).
FORCE_NODE_CAPACITY = "galends/force-node-capacity"


def get_node_forced_gpu_capacity(node) -> Optional[int]:
    """Read the ``galends/force-node-capacity`` annotation from *node*.

    Returns the GPU count an operator has forced this node to contribute, or
    ``None`` when the annotation is absent, empty, or unusable — in which case
    the caller keeps whatever ``status.allocatable`` reported.

    ``0`` is a **valid** override, and deliberately not rejected the way
    ``get_pod_min_runtime_seconds`` rejects it: masking a node's GPUs from the
    reservation system without cordoning it is the main thing this annotation is
    for, and cordoning is not the same act — it also stops every non-GPU pod and
    is what ``snapshot_node_gpu_inventory`` already treats as "gone entirely".
    A **negative** value is rejected, because a node cannot contribute negative
    capacity and summing one into its class's total would silently eat another
    node's real GPUs.  Junk is rejected for the same tolerant-parsing reason
    ``config.py`` rejects a junk interval — with a WARNING naming the annotation,
    so an operator who set something and saw no effect can find out why.
    """
    annotations: dict = getattr(node.metadata, "annotations", None) or {}
    raw = annotations.get(FORCE_NODE_CAPACITY)
    if raw is None or str(raw).strip() == "":
        return None
    value: Optional[int]
    try:
        value = int(str(raw).strip())
    except (ValueError, TypeError):
        value = None
    if value is None or value < 0:
        log.warning("%s", kv(
            event="k8s.node_capacity_forced_invalid", node=node.metadata.name,
            annotation=FORCE_NODE_CAPACITY, value=raw,
        ))
        return None
    return value


async def snapshot_node_gpu_inventory(
    taint_key: str, gpu_resource: str = "nvidia.com/gpu"
) -> dict[str, dict[str, int]]:
    """Return allocatable GPUs per GPU-class label, broken down **per node**.

    LISTs all nodes and, for each node carrying a *taint_key* taint, records
    ``status.allocatable[gpu_resource]`` under ``{taint_value: {node_name: gpus}}``
    (the GPU-class label mirrors the toleration the controller applies to pods).
    Nodes that are cordoned (``spec.unschedulable``) or being deleted are
    excluded — their GPUs are not placeable.

    A node carrying the ``galends/force-node-capacity`` annotation contributes
    that number instead of its allocatable count (see
    ``get_node_forced_gpu_capacity``).  This is the **only** place the override
    is applied, which is what makes it total: every notion of physical capacity
    in the controller — per-class totals, free capacity, headroom, the capacity
    audit, and the per-node feasibility guards — is derived from this one map.

    This is the per-node primitive: ``snapshot_node_gpu_capacity`` collapses it
    to per-class totals for consumers that only need the aggregate, while
    per-node accounting (whether any *single* node can host a multi-GPU pod)
    reads the breakdown directly.
    """
    log.debug("%s", kv(event="k8s.list_nodes", purpose="gpu_inventory"))
    node_list = await _run(_core_v1.list_node)
    inventory: dict[str, dict[str, int]] = {}
    for node in node_list.items:
        if node.spec and node.spec.unschedulable:
            continue
        if node.metadata.deletion_timestamp is not None:
            continue
        taints = node.spec.taints if (node.spec and node.spec.taints) else []
        classes = {t.value for t in taints if t.key == taint_key and t.value}
        if not classes:
            continue
        allocatable = (node.status.allocatable or {}) if node.status else {}
        raw = allocatable.get(gpu_resource, "0")
        try:
            gpus = int(raw)
        except (ValueError, TypeError):
            log.warning("%s", kv(
                event="k8s.node_allocatable_invalid", node=node.metadata.name,
                resource=gpu_resource, value=raw,
            ))
            gpus = 0
        forced = get_node_forced_gpu_capacity(node)
        if forced is not None:
            # The override replaces the *result* of the allocatable read rather
            # than short-circuiting it, so a node whose allocatable is also
            # unparseable still reports that separately — being overridden is
            # not a reason to stop saying the underlying reading is broken.
            log.debug("%s", kv(
                event="k8s.node_capacity_forced", node=node.metadata.name,
                total=forced,
            ))
            gpus = forced
        for gpu_class in classes:
            inventory.setdefault(gpu_class, {})[node.metadata.name] = gpus
    # The inventory is a nested map, so it is fanned out to one line per class
    # rather than emitted as a dict inside a single field.
    for _cls, _nodes in sorted(inventory.items()):
        log.debug("%s", kv(
            event="k8s.node_inventory", clabel=_cls,
            nodes=len(_nodes), total=sum(_nodes.values()),
        ))
    return inventory


async def snapshot_node_gpu_capacity(
    taint_key: str, gpu_resource: str = "nvidia.com/gpu"
) -> dict[str, int]:
    """Return total allocatable GPUs per GPU-class label, from node taints.

    Thin per-class collapse of ``snapshot_node_gpu_inventory`` (one node LIST,
    summed across the nodes of each class).  Feeds preemption planning's and the
    capacity audit's notion of physical capacity per class; the controller has
    no other source of "how many GPUs actually exist".
    """
    inventory = await snapshot_node_gpu_inventory(taint_key, gpu_resource)
    return {
        gpu_class: sum(per_node.values())
        for gpu_class, per_node in inventory.items()
    }


async def apply_toleration(
    pod_name: str,
    namespace: str,
    pod,
    tol_key: str,
    tol_value: str,
    booking_reference: str,
) -> None:
    """Patch *pod* to add toleration ``tol_key=tol_value:NoSchedule`` and set
    the ``galends/booking-reference`` annotation.

    The booking-reference is the single key from which occupancy is later
    reconstructed (see parse_booking_reference).  The patch preserves all
    existing tolerations; Kubernetes rejects requests that would remove
    tolerations from running pods.
    """
    new_tol = {
        "key": tol_key,
        "operator": "Equal",
        "value": tol_value,
        "effect": "NoSchedule",
    }

    # Serialise existing tolerations into plain dicts for the patch body.
    existing: list[dict] = []
    for t in pod.spec.tolerations or []:
        entry: dict = {
            "key": t.key,
            "operator": t.operator,
            "effect": t.effect,
        }
        if t.value is not None:
            entry["value"] = t.value
        if t.toleration_seconds is not None:
            entry["tolerationSeconds"] = t.toleration_seconds
        existing.append(entry)

    patch = {
        "metadata": {"annotations": {"galends/booking-reference": booking_reference}},
        "spec": {"tolerations": existing + [new_tol]},
    }
    log.debug("%s", kv(
        event="k8s.patch_pod", ns=namespace, pod=pod_name, patch="toleration",
        tol_key=tol_key, tol_value=tol_value, booking_ref=booking_reference,
    ))
    await _run(_core_v1.patch_namespaced_pod, pod_name, namespace, patch)
    log.info("%s", kv(
        event="pod.toleration_applied", ns=namespace, pod=pod_name,
        tol_key=tol_key, tol_value=tol_value, booking_ref=booking_reference,
    ))


async def remove_scheduling_gate(
    pod_name: str, namespace: str, pod, gate_name: str
) -> None:
    """Remove *gate_name* from pod.spec.schedulingGates if present.

    Uses the strategic-merge-patch ``$patch: delete`` directive so only the
    named gate is removed; any other gates on the pod are preserved.
    """
    existing_gates = pod.spec.scheduling_gates or []
    if not any(g.name == gate_name for g in existing_gates):
        log.debug("%s", kv(
            event="pod.gate_absent", ns=namespace, pod=pod_name, gate=gate_name,
        ))
        return

    patch = {"spec": {"schedulingGates": [{"name": gate_name, "$patch": "delete"}]}}
    log.debug("%s", kv(
        event="k8s.patch_pod", ns=namespace, pod=pod_name,
        patch="gate_remove", gate=gate_name,
    ))
    await _run(_core_v1.patch_namespaced_pod, pod_name, namespace, patch)
    log.info("%s", kv(
        event="pod.gate_removed", ns=namespace, pod=pod_name, gate=gate_name,
    ))


async def annotate_runtime_guarantee(
    pod_name: str,
    namespace: str,
    seconds: int,
    guaranteed_until: datetime,
    facts: ReservationFacts,
    admitted_at: Optional[datetime] = None,
) -> None:
    """Annotate *pod_name* with its runtime guarantee and the reservation behind it.

    Writes ``galends/pod-runtime-limit-seconds`` (the guaranteed duration in
    seconds, consumed by in-pod countdown widgets), ``galends/guaranteed-until``
    (the same instant as an absolute UTC ISO-8601 timestamp), and
    ``galends/guarantee-status`` (``"guaranteed"`` — recording a guarantee always
    means the pod is inside one; the reconcile in ``main`` flips this to
    ``"overstay"`` once the guarantee lapses).

    It also stamps *facts* — the reservation's kind, own window, reserved GPU
    count, and display name of its GPU class — in the **same patch**, so the
    whole descriptive set costs no extra API call.  Because these describe the
    reservation the pod is currently linked to, every caller that re-links a pod
    (adoption, lease-to-booking merge) must call this again with the new
    reservation or the stamps would keep describing the old one.
    ``admitted_at`` is passed only on a pod's **first** admission, and is
    omitted (left at whatever the pod already carries) on those re-links.

    Re-linking is not the only way the facts can go stale: the *same*
    reservation can be mutated underneath the pod (a lease window extended in
    place), which reaches none of those callers.  ``annotate_reservation_facts``
    plus the per-tick ``main._apply_reservation_facts`` reconcile cover that
    case; this function stays the admission/re-link writer.

    Informational only: this never patches ``spec.activeDeadlineSeconds`` —
    demand-driven preemption enforces nothing through a Kubernetes-side
    deadline, and never reads these annotations back to make a decision; it
    recomputes the guarantee live from reservation state
    (``ControllerState.guarantee_end``).
    """
    until_str = utc_iso(guaranteed_until)
    log.debug("%s", kv(
        event="k8s.patch_pod", ns=namespace, pod=pod_name, patch="runtime_guarantee",
        guarantee_s=seconds, until=until_str,
    ))
    annotations = {
        "galends/pod-runtime-limit-seconds": str(seconds),
        "galends/guaranteed-until": until_str,
        GUARANTEE_STATUS: GUARANTEE_STATUS_GUARANTEED,
        RESERVATION_KIND: facts.kind,
        RESERVATION_START: utc_iso(facts.start_utc),
        RESERVATION_END: utc_iso(facts.end_utc),
        RESERVATION_GPU_COUNT: str(facts.gpu_count),
        GPU_CLASS_NAME: facts.gpu_class_name,
    }
    if admitted_at is not None:
        annotations[ADMITTED_AT] = utc_iso(admitted_at)
    patch = {"metadata": {"annotations": annotations}}
    await _run(_core_v1.patch_namespaced_pod, pod_name, namespace, patch)
    log.info("%s", kv(
        event="pod.guarantee_recorded", ns=namespace, pod=pod_name,
        guarantee_s=seconds, until=until_str,
    ))


async def annotate_reservation_facts(
    pod_name: str,
    namespace: str,
    facts: ReservationFacts,
) -> None:
    """Re-stamp *pod_name*'s reservation-fact annotations from *facts*.

    ``annotate_runtime_guarantee`` writes these at admission and on every
    **re-link** (adoption, lease-to-booking merge), which covers every way the
    pod's reservation could change *identity*.  This covers the remaining way it
    can change *content*: the same reservation being mutated underneath the pod
    — an on-demand lease whose window is extended in place, which re-links
    nothing and so reaches none of those callers.  Without it the pod would keep
    advertising its pre-extension ``galends/reservation-end`` while
    ``galends/guaranteed-until`` moved forward, and a consumer reading both
    would see them contradict each other.

    Writes only the five fact keys.  It deliberately does **not** touch
    ``galends/guarantee-status`` / ``-guaranteed-until`` (owned by
    ``annotate_guarantee_status``, which reconciles them from live chain-aware
    state) or ``galends/admitted-at`` (stamped once, at first admission — a
    session-elapsed clock that must never restart mid-job).

    Informational only, like every other ``galends`` stamp: never enforced
    Kubernetes-side and never read back to make a decision.
    """
    end_str = utc_iso(facts.end_utc)
    log.debug("%s", kv(
        event="k8s.patch_pod", ns=namespace, pod=pod_name,
        patch="reservation_facts", end=end_str,
    ))
    patch = {
        "metadata": {
            "annotations": {
                RESERVATION_KIND: facts.kind,
                RESERVATION_START: utc_iso(facts.start_utc),
                RESERVATION_END: end_str,
                RESERVATION_GPU_COUNT: str(facts.gpu_count),
                GPU_CLASS_NAME: facts.gpu_class_name,
            }
        },
    }
    await _run(_core_v1.patch_namespaced_pod, pod_name, namespace, patch)
    log.info("%s", kv(
        event="pod.facts_refreshed", ns=namespace, pod=pod_name, end=end_str,
    ))


async def annotate_guarantee_status(
    pod_name: str,
    namespace: str,
    status: str,
    guaranteed_until: Optional[datetime],
) -> None:
    """Update *pod_name*'s live ``galends/guarantee-status`` (+ ``guaranteed-until``).

    Writes ``galends/guarantee-status`` (``"guaranteed"`` | ``"overstay"``) and,
    **only when** *guaranteed_until* is provided, refreshes
    ``galends/guaranteed-until`` to that absolute UTC ISO-8601 instant.  For an
    overstay pod *guaranteed_until* is ``None`` so the existing (now-past)
    ``guaranteed-until`` value is left frozen — only the status key flips.
    Informational only, mirroring ``annotate_runtime_guarantee``: nothing is
    enforced Kubernetes-side and these are never read back to make a decision.
    """
    annotations: dict = {GUARANTEE_STATUS: status}
    if guaranteed_until is not None:
        annotations["galends/guaranteed-until"] = utc_iso(guaranteed_until)
    log.debug("%s", kv(
        event="k8s.patch_pod", ns=namespace, pod=pod_name,
        patch="guarantee_status", gstatus=status,
    ))
    patch = {"metadata": {"annotations": annotations}}
    await _run(_core_v1.patch_namespaced_pod, pod_name, namespace, patch)
    log.info("%s", kv(event="pod.guarantee_status", ns=namespace, pod=pod_name, gstatus=status))


