def init_k8s(
    kubeconfig_path: Optional[str], *, strict_tls_verify: bool = True
) -> None:
    """Load Kubernetes credentials and create the API clients.

    *strict_tls_verify* is ``K8S_TLS_STRICT_VERIFY``; ``False`` relaxes the
    OpenSSL strict X.509 checks on the API server connection — see
    ``_relax_strict_tls_verify`` for what that does and does not give up.
    """
    global _core_v1, _coordination_v1
    if kubeconfig_path:
        k8s_config.load_kube_config(config_file=kubeconfig_path)
        log.info("%s", kv(event="k8s.auth", mode="kubeconfig", path=kubeconfig_path))
    else:
        k8s_config.load_incluster_config()
        log.info("%s", kv(event="k8s.auth", mode="in_cluster"))
    _core_v1 = k8s_client.CoreV1Api()
    _coordination_v1 = k8s_client.CoordinationV1Api()
    if not strict_tls_verify:
        _relax_strict_tls_verify(_core_v1.api_client, _coordination_v1.api_client)
        log.warning("%s", kv(
            event="k8s.tls_relaxed",
            name="K8S_TLS_STRICT_VERIFY",
            detail=(
                "strict X.509 checks disabled on the Kubernetes API connection; "
                "chain, validity and hostname are still verified"
            ),
        ))


def _relax_strict_tls_verify(*api_clients) -> None:
    """Clear ``VERIFY_X509_STRICT`` on each API client's connection pool.

    Python 3.13's ``ssl.create_default_context()`` turns on
    ``VERIFY_X509_STRICT``, and urllib3 2.x mirrors that in the context it
    builds for every HTTPS pool.  Under that flag OpenSSL requires an Authority
    Key Identifier extension on the certificates it chains through, which a
    cluster PKI generated by older tooling may not carry.  The connection then
    fails with ``CERTIFICATE_VERIFY_FAILED ... Missing Authority Key
    Identifier`` even though the service account's ``ca.crt`` is mounted and
    correct — the same image on Python 3.12 connected fine.  Regenerating the
    apiserver certificate with an AKID is the real fix; this is the escape
    hatch for a cluster where that is not immediately possible.

    It is deliberately **not** ``verify_ssl: false``.  The chain is still built
    and verified against the mounted CA, validity dates still apply, and the
    hostname is still matched; only the AKID-presence requirement is dropped.
    The context is otherwise exactly the one urllib3 would have built for this
    client, so nothing else about the TLS posture changes, and the CA file is
    still loaded into it by ``ssl_wrap_socket`` at connect time.

    Every API client owns its own ``RESTClientObject``, hence its own pool
    manager, so each is handed its own context.  Pool objects are built lazily
    from ``connection_pool_kw`` on first use, which is why this runs at startup
    before any request: a pool that already existed would keep the strict
    context it was created with.
    """
    for api_client in api_clients:
        pool_kw = api_client.rest_client.pool_manager.connection_pool_kw
        context = create_urllib3_context(cert_reqs=pool_kw.get("cert_reqs"))
        context.verify_flags &= ~ssl.VERIFY_X509_STRICT
        pool_kw["ssl_context"] = context


